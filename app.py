from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

import pandas as pd
from cravat import Cravat
from pydantic.dataclasses import dataclass
from pyfedappwrap.learning.app_types import BaseSelfLearnedApp
from pyfedappwrap.learning.run_runfig import AppConfig, AppInputConfig, AppOutputConfig
from typing_extensions import override


@dataclass
class OpenCravatConfig(AppConfig):
    assembly: str = "hg38"
    annotators: str = "clinvar"
    reporters: str = "text"
    preview_rows: int = 100


@dataclass
class OpenCravatInput(AppInputConfig):
    variant_file: Path | None = None


@dataclass
class OpenCravatOutput(AppOutputConfig):
    status_json: Path | None = None
    log_file: Path | None = None
    err_file: Path | None = None

    variant_preview: Any | None = None
    gene_preview: Any | None = None
    report_files: list[str] | None = None
    report: Any | None = None


class OpenCravatApp(
    BaseSelfLearnedApp[OpenCravatConfig, OpenCravatInput, OpenCravatOutput]
):
    def __init__(self):
        super().__init__()

    def run_algorithm(self, data: OpenCravatInput) -> OpenCravatOutput:
        input_path = self._normalize_input_path(data.variant_file)
        run_name = self._build_run_name(input_path)
        output_dir = Path("data") / "opencravat" / run_name
        output_dir.mkdir(parents=True, exist_ok=True)

        self._run_opencravat(
            input_path=input_path,
            output_dir=output_dir,
            run_name=run_name,
        )

        output = OpenCravatOutput()
        output.status_json = self._existing_file(output_dir / f"{run_name}.status.json")
        output.log_file = self._existing_file(output_dir / f"{run_name}.log")
        output.err_file = self._existing_file(output_dir / f"{run_name}.err")
        output.report_files = self._collect_report_files(output_dir, run_name)

        output.report = self._build_report(
            input_path=input_path,
            output=output,
        )
        return output

    def _run_opencravat(self, input_path: Path, output_dir: Path, run_name: str) -> None:
        kwargs: dict[str, Any] = {
            "inputs": [str(input_path)],
            "output_dir": str(output_dir),
            "run_name": run_name,
            "annotators": [name.strip() for name in (self.config.annotators or "").split(",") if name.strip()],
            "reports": [name.strip() for name in (self.config.reporters or "").split(",") if name.strip()],
            "genome": self.config.assembly,
        }

        runner = Cravat(**kwargs)
        runner.run()

    def _normalize_input_path(self, value: Path | str | None) -> Path:
        if value is None:
            raise ValueError("OpenCravatInput.variant_file ist erforderlich.")

        path = Path(value)
        if not path.exists():
            raise FileNotFoundError(f"Variantendatei nicht gefunden: {path}")

        if not path.is_file():
            raise ValueError(f"Pfad ist keine Datei: {path}")

        return path.resolve()

    def _build_run_name(self, input_path: Path) -> str:
        stem = input_path.name
        for suffix in [".vcf.gz", ".vcf", ".tsv.gz", ".tsv", ".txt.gz", ".txt"]:
            if stem.endswith(suffix):
                stem = stem[: -len(suffix)]
                break

        clean = "".join(ch if ch.isalnum() or ch in {"-", "_"} else "_" for ch in stem)
        return f"{clean}_opencravat"

    def _existing_file(self, path: Path) -> Path | None:
        return path if path.exists() else None

    def _collect_report_files(self, output_dir: Path, run_name: str) -> list[str]:
        files = []
        for p in sorted(output_dir.glob(f"{run_name}.*")):
            if p.is_file():
                files.append(str(p))
        return files

    def _build_report(
            self,
            input_path: Path,
            output: OpenCravatOutput,
    ) -> str:
        status_summary = self._read_status_json(output.status_json)

        variant_rows = (
            len(output.variant_preview)
            if isinstance(output.variant_preview, pd.DataFrame)
            else 0
        )
        gene_rows = (
            len(output.gene_preview)
            if isinstance(output.gene_preview, pd.DataFrame)
            else 0
        )

        report_parts = [
            "<h1>OpenCRAVAT annotation report</h1>",
            "<p>Generated by the PoSyMed OpenCravat app.</p>",
            "<h2>Run configuration</h2>",
            "<ul>",
            f"<li>Input file: {input_path}</li>",
            f"<li>Assembly: {self.config.assembly}</li>",
            f"<li>Annotators: {self.config.annotators or 'none'}</li>",
            f"<li>Reporters: {self.config.reporters or 'none'}</li>",
            "</ul>",
            "<h2>Artifacts</h2>",
            "<ul>",
            f"<li>Status JSON: {output.status_json or 'not found'}</li>",
            f"<li>Log file: {output.log_file or 'not found'}</li>",
            f"<li>Error file: {output.err_file or 'not found'}</li>",
            f"<li>Generated files: {len(output.report_files or [])}</li>",
            "</ul>",
        ]

        if status_summary:
            report_parts.append("<h2>Status summary</h2>")
            report_parts.append("<ul>")
            for key in ["status", "run_name", "assembly", "submission_time", "annotators",
                        "reports"]:
                if key in status_summary:
                    value = status_summary[key]
                    if isinstance(value, list):
                        value = ", ".join(map(str, value))
                    report_parts.append(f"<li>{key}: {value}</li>")
            report_parts.append("</ul>")

        if isinstance(output.variant_preview, pd.DataFrame) and not output.variant_preview.empty:
            report_parts.append(f"<h2>Variant preview ({variant_rows} rows)</h2>")
            report_parts.append(output.variant_preview.head(25).to_html(index=False))

        if isinstance(output.gene_preview, pd.DataFrame) and not output.gene_preview.empty:
            report_parts.append(f"<h2>Gene preview ({gene_rows} rows)</h2>")
            report_parts.append(output.gene_preview.head(25).to_html(index=False))

        if output.report_files:
            report_parts.append("<h2>Generated files</h2>")
            report_parts.append(
                "<ul>"
                + "".join(f"<li>{Path(p).name}</li>" for p in output.report_files)
                + "</ul>"
            )

        return "\n".join(report_parts)

    def _read_status_json(self, path: Path | None) -> dict[str, Any]:
        if path is None or not path.exists():
            return {}
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            return {}

    @override
    def get_test_data(self) -> Optional[dict[str, Path]]:
        return {
            "variant_file": Path("data/file.vcf")
        }

    @override
    def get_test_hyperparams(self) -> Optional[dict[str, Any]]:
        return {
            "assembly": "hg38",
            "annotators": "clinvar",
            "reporters": "text",
            "preview_rows": 100
        }
